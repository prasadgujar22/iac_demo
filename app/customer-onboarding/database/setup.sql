CREATE USER customer_app IDENTIFIED BY customer_app;
GRANT CONNECT, RESOURCE TO customer_app;

ALTER USER customer_app QUOTA UNLIMITED ON USERS;

CREATE TABLE customer_app.CUSTOMER_ONBOARDING (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(150) NOT NULL,
    COMPANY_NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PHONE_NUMBER VARCHAR2(30),
    ADDRESS_LINE1 VARCHAR2(200),
    ADDRESS_LINE2 VARCHAR2(200),
    CITY VARCHAR2(80),
    STATE VARCHAR2(80),
    POSTAL_CODE VARCHAR2(20),
    COUNTRY VARCHAR2(80),
    ONBOARDING_STATUS VARCHAR2(40) NOT NULL,
    NOTES VARCHAR2(500),
    CREATED_DATE DATE DEFAULT SYSDATE NOT NULL
);
